"""How much seizure and background signal each removal rule keeps (ICLabel report, Section 6).

For every recording with cached decompositions (results_v2/iclabel/<subject>/ica/, written
by src/iclabel_p6_match.py) the signal is cleaned four ways and compared with the
uncleaned signal, in the view the models see: the 18 bipolar channels, 256 Hz,
0.5 to 40 Hz.

    rule A   remove the components the P6 frontopolar rule flags in the ICLabel ICA
    rule B   remove the components ICLabel calls eye blink
    rule C   keep only the components ICLabel calls brain
    P6       the actual P6a cleaning used in the paper (its own bipolar ICA)

Rules A to C start from the ICLabel-preprocessed signal (1 to 100 Hz, average reference);
after the bipolar conversion and the 0.5 to 40 Hz band-pass this is a 1 to 40 Hz view.
P6 starts from its own input (src/siena.py: read_bipolar, 0.5 to 40 Hz). Kept power is
sum(cleaned^2) / sum(uncleaned^2) over seizure samples and over background samples
separately; excluded intervals count as neither. No ICA is fitted here.

Usage: .venv-ica/Scripts/python -W ignore -m src.iclabel_power
Output: results_v2/iclabel/power_kept.csv, power_kept.md
"""
from __future__ import annotations

import json
import sys

import numpy as np
import pandas as pd
from scipy.signal import resample_poly

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except (AttributeError, ValueError):
    pass

from .chbmit import FS_CHB
from .iclabel_check import OUT_ROOT, ictal_mask, prepare, read_referential
from .iclabel_p6_match import P6_BAND, to_bipolar
from .preprocess import _mne_raw, bandpass
from .siena import read_bipolar, record_path

PATIENTS = ("PN00", "PN12", "PN14", "PN10", "PN17")


def kept(clean, orig, ictal, back):
    c, o = clean ** 2, orig ** 2
    return (float(c[:, ictal].sum() / o[:, ictal].sum()),
            float(c[:, back].sum() / o[:, back].sum()))


def bipolar_view(data, names, fs):
    y = resample_poly(to_bipolar(data, names), 1, int(fs // FS_CHB), axis=-1)
    return bandpass(y * 1e6, FS_CHB, *P6_BAND).astype(np.float64)


def record_power(subject, stem, out):
    import mne
    name = f"{stem}.edf"
    path = record_path(subject, name)
    keep = out / "ica"
    part = out / f"components_{stem}.csv"
    comp = pd.read_csv(part) if part.exists() else \
        pd.read_csv(out / "components.csv").query("record == @name").reset_index(drop=True)
    rules = {"A": comp.index[comp["p6_rule"]].tolist(),
             "B": comp.index[comp["iclabel"] == "eye blink"].tolist(),
             "C": comp.index[comp["iclabel"] != "brain"].tolist()}

    eeg = prepare(read_referential(path)).pick("eeg")
    fs = eeg.info["sfreq"]
    ica = mne.preprocessing.read_ica(keep / f"iclabel_{stem}-ica.fif", verbose=False)
    orig = bipolar_view(eeg.get_data(), eeg.ch_names, fs)
    n = orig.shape[1]
    ictal, skip, _ = ictal_mask(path, subject, n, FS_CHB)
    back = ~ictal & ~skip
    rows = []
    for r, exc in rules.items():
        clean = bipolar_view(ica.apply(eeg.copy(), exclude=exc).get_data(), eeg.ch_names, fs)
        ki, kb = kept(clean, orig, ictal, back)
        rows.append({"record": name, "rule": r, "n_removed": len(exc),
                     "kept_seizure": ki, "kept_background": kb})

    p6 = mne.preprocessing.read_ica(keep / f"p6a_{stem}-ica.fif", verbose=False)
    p6.exclude = json.loads((keep / f"p6a_{stem}.json").read_text(encoding="utf-8"))["removed"]
    x = bandpass(read_bipolar(path), FS_CHB, *P6_BAND)
    clean = p6.apply(_mne_raw(x, FS_CHB)).get_data() * 1e6
    x = x.astype(np.float64)
    ictal, skip, _ = ictal_mask(path, subject, x.shape[1], FS_CHB)
    ki, kb = kept(clean, x, ictal, ~ictal & ~skip)
    rows.append({"record": name, "rule": "P6", "n_removed": len(p6.exclude),
                 "kept_seizure": ki, "kept_background": kb})
    for r in rows:
        r["subject"] = subject
        print(f"{name} {r['rule']:>2}: {r['n_removed']:2d} removed, kept seizure "
              f"{r['kept_seizure']:.3f}, background {r['kept_background']:.3f}", flush=True)
    return rows


def main():
    rows = []
    for s in PATIENTS:
        out = OUT_ROOT / s
        for f in sorted((out / "ica").glob("iclabel_*-ica.fif")):
            stem = f.name.removeprefix("iclabel_").removesuffix("-ica.fif")
            if (out / "ica" / f"p6a_{stem}.json").exists():
                rows += record_power(s, stem, out)
    df = pd.DataFrame(rows)[["subject", "record", "rule", "n_removed",
                             "kept_seizure", "kept_background"]]
    df.to_csv(OUT_ROOT / "power_kept.csv", index=False)
    lines = ["# Seizure and background power kept by each removal rule", "",
             "Generated by `python -m src.iclabel_power`; do not edit by hand. Bipolar "
             "18 channels, 256 Hz, 0.5 to 40 Hz. A: P6 frontopolar rule in the ICLabel ICA; "
             "B: ICLabel eye; C: ICLabel brain only; P6: the actual P6a cleaning.", "",
             "| Recording | A seizure / background | B | C | P6 |", "|---|---|---|---|---|"]
    for name, d in df.groupby("record", sort=False):
        cell = {r.rule: f"{r.kept_seizure:.2f} / {r.kept_background:.2f} ({r.n_removed})"
                for r in d.itertuples()}
        lines.append(f"| {name.removesuffix('.edf')} | {cell['A']} | {cell['B']} | "
                     f"{cell['C']} | {cell['P6']} |")
    lines += ["", "Each cell: kept seizure / kept background power (components removed)."]
    (OUT_ROOT / "power_kept.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
